import 'dart:io';

enum AppLanguage { es, en, pt }

AppLanguage _detectLanguage() {
  final locale = Platform.localeName.toLowerCase();
  if (locale.startsWith('pt')) return AppLanguage.pt;
  if (locale.startsWith('en')) return AppLanguage.en;
  return AppLanguage.es; // Default Spanish
}

final AppLanguage currentLanguage = _detectLanguage();

String t(String key) {
  return _translations[currentLanguage]?[key] ?? _translations[AppLanguage.es]?[key] ?? key;
}

